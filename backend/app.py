
import os
from functools import wraps

import psycopg
from psycopg.rows import dict_row
from flask import Flask, jsonify, request, session
from flask_cors import CORS
from werkzeug.security import generate_password_hash, check_password_hash


app = Flask(__name__)

secret = os.environ.get("SECRET_KEY")
if not secret and os.environ.get("FLASK_ENV") == "production":
    raise RuntimeError("Set SECRET_KEY in the production environment.")

app.config.update(
    SECRET_KEY=secret or "LOCAL-ONLY-CHANGE-THIS-SECRET",
    SESSION_COOKIE_HTTPONLY=True,
    SESSION_COOKIE_SAMESITE=os.environ.get(
        "SESSION_COOKIE_SAMESITE", "Lax"
    ),
    SESSION_COOKIE_SECURE=os.environ.get(
        "SESSION_COOKIE_SECURE", "false"
    ).lower() == "true",
)

FRONTEND_ORIGIN = os.environ.get(
    "FRONTEND_ORIGIN", "http://127.0.0.1:8000"
).rstrip("/")

DATABASE_URL = os.environ.get("DATABASE_URL")

CORS(
    app,
    resources={r"/api/*": {"origins": [FRONTEND_ORIGIN]}},
    supports_credentials=True,
)


def connect_db():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is not configured.")

    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=10,
    )


def init_db():
    with connect_db() as db:
        db.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(120) NOT NULL,
                email VARCHAR(254) NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """
        )


def require_login(fn):
    @wraps(fn)
    def wrapped(*args, **kwargs):
        if not session.get("user_id"):
            return jsonify(message="Please sign in first."), 401
        return fn(*args, **kwargs)

    return wrapped


@app.get("/")
def home():
    return jsonify(status="running", service="generated-app-api")


@app.get("/health")
def health():
    try:
        with connect_db() as db:
            db.execute("SELECT 1")
        return jsonify(status="healthy", database="connected"), 200
    except Exception:
        app.logger.exception("Database health check failed")
        return jsonify(status="unhealthy", database="unavailable"), 503


@app.post("/api/auth/register")
def register():
    data = request.get_json(silent=True) or {}

    username = str(data.get("username", "")).strip()
    email = str(data.get("email", "")).strip().lower()
    password = data.get("password", "")

    if (
        not username
        or len(username) > 120
        or not email
        or len(email) > 254
    ):
        return jsonify(message="Enter a valid name and email."), 400

    if (
        not isinstance(password, str)
        or len(password) < 8
        or len(password) > 1024
    ):
        return jsonify(
            message="Password must be at least 8 characters."
        ), 400

    try:
        with connect_db() as db:
            user = db.execute(
                """
                INSERT INTO users (username, email, password_hash)
                VALUES (%s, %s, %s)
                ON CONFLICT (email) DO NOTHING
                RETURNING id, username, email
                """,
                (
                    username,
                    email,
                    generate_password_hash(password),
                ),
            ).fetchone()

        if user is None:
            return jsonify(
                message="An account with this email already exists."
            ), 409

    except Exception:
        app.logger.exception("Registration failed")
        return jsonify(message="Could not create the account."), 500

    session.clear()
    session["user_id"] = user["id"]
    session["username"] = user["username"]

    return jsonify(
        message="Account created.",
        user={
            "id": user["id"],
            "username": user["username"],
            "email": user["email"],
        },
    ), 201


@app.post("/api/auth/login")
def login():
    data = request.get_json(silent=True) or {}

    email = str(data.get("email", "")).strip().lower()
    password = data.get("password", "")

    if not isinstance(password, str):
        return jsonify(message="Invalid email or password."), 401

    try:
        with connect_db() as db:
            user = db.execute(
                """
                SELECT id, username, email, password_hash
                FROM users
                WHERE email = %s
                """,
                (email,),
            ).fetchone()

    except Exception:
        app.logger.exception("Login database query failed")
        return jsonify(message="Could not sign in right now."), 500

    if not user or not check_password_hash(
        user["password_hash"], password
    ):
        return jsonify(message="Invalid email or password."), 401

    session.clear()
    session["user_id"] = user["id"]
    session["username"] = user["username"]

    return jsonify(
        message="Signed in.",
        user={
            "id": user["id"],
            "username": user["username"],
            "email": user["email"],
        },
    )


@app.get("/api/auth/me")
@require_login
def me():
    try:
        with connect_db() as db:
            user = db.execute(
                """
                SELECT id, username, email
                FROM users
                WHERE id = %s
                """,
                (session["user_id"],),
            ).fetchone()

    except Exception:
        app.logger.exception("User lookup failed")
        return jsonify(message="Could not load your account."), 500

    if not user:
        session.clear()
        return jsonify(message="Please sign in again."), 401

    return jsonify(
        user={
            "id": user["id"],
            "username": user["username"],
            "email": user["email"],
        }
    )


@app.post("/api/auth/logout")
def logout():
    session.clear()
    return jsonify(message="Signed out.")


@app.errorhandler(404)
def not_found(_error):
    return jsonify(message="Endpoint not found."), 404


@app.errorhandler(500)
def server_error(_error):
    app.logger.exception("Unhandled server error")
    return jsonify(message="Internal server error."), 500


init_db()


if __name__ == "__main__":
    app.run(
        host="127.0.0.1",
        port=int(os.environ.get("PORT", "5001")),
        debug=False,
    )
